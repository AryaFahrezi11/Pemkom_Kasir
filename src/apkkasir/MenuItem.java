    private boolean showing = false;
    private void formMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_formMousePressed
        // Ubah warna background menjadi putih ketika di-klik
         setBackground(new java.awt.Color(255,255,255));
        if (act != null) {
            act.actionPerformed(null);
        }
        if (lastClickedMenu != null && lastClickedMenu != this) {
            lastClickedMenu.setBackground(lastClickedMenu.originalColor); // Kembalikan warna menu sebelumnya
        }
        lastClickedMenu = this; // Simpan menu yang terakhir di-klik
        if (showing) {
            hideMenu();
        } else {
            showMenu();
        }
    }//GEN-LAST:event_formMousePressed


