    private void formMouseEntered(MouseEvent evt) {
        // Ketika mouse masuk ke item menu, ubah warnanya jika belum di-klik
        if (this.getBackground() != Color.WHITE) {
            setBackground(new java.awt.Color(204, 255, 255)); // Warna saat mouse hover
        }
    }

    private void formMouseExited(MouseEvent evt) {
        // Ketika mouse keluar dari item menu, kembalikan warna jika belum di-klik
        if (this.getBackground() != Color.WHITE) {
            setBackground(originalColor); // Kembali ke warna asli
        }
    }
    
    private void hideMenu() {
        new Thread (new Runnable() {
            @Override
            public void run() {
                for (int i = subMenu.size() - 1; i >= 0; i--){
                    sleep();
                    subMenu.get(i).setVisible(false);
                    subMenu.get(i).hideMenu();
                }
                getParent().repaint();
                getParent().revalidate();
                showing = false;
            }
        }).start();
    }

    private void showMenu() {
        new Thread (new Runnable() {
            @Override
            public void run() {
                for (int i = 0; i < subMenu.size(); i++){
                    sleep();
                    subMenu.get(i).setVisible(true);
                }
                showing = true;
                getParent().repaint();
                getParent().revalidate();
                
            }
        }).start();
        
    }
    
    private void sleep() {
        try{
            Thread.sleep(20);
        } catch (Exception e) {
        }
    }
